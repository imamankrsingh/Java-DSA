public class multiplevariables {
    public static void main(String[] args) {
        int x = 5, y = 8, z = 9;
        
        System.out.println("the value of x is : "+x);
     
        System.out.println(y);
        z = 10;
        
        System.out.println(z);
        System.out.println(x+y+z);

    }
}
